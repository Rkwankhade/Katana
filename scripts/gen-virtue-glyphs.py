#!/usr/bin/env python3
"""Outlines the kanji used by the katana reveal into SVG path data, so the sword never depends on a visitor's installed fonts.

    python3 scripts/gen-virtue-glyphs.py            (needs fontTools and Noto Serif CJK JP)

Source face: Noto Serif CJK JP Bold (SIL Open Font License 1.1, https://openfontlicense.org), whose licence permits embedding
glyph outlines in derived artwork. Output: src/data/virtue-glyphs.ts, one path per character in a 1000 unit em box, y pointing down.
"""
import sys
from fontTools.ttLib import TTCollection
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

SRC = '/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc'
CHARS = '義勇仁礼誠名誉忠'  # every distinct character in the seven virtue markings

font = next((f for f in TTCollection(SRC).fonts if f['name'].getDebugName(1) == 'Noto Serif CJK JP'), None)
if font is None:
    sys.exit('Noto Serif CJK JP face not found in ' + SRC)
cmap, gs = font.getBestCmap(), font.getGlyphSet()
assert font['head'].unitsPerEm == 1000

def round_path(d: str) -> str:
    out, num = [], ''
    for ch in d + ' ':
        if ch in '-0123456789.':
            num += ch
        else:
            if num:
                out.append(str(int(round(float(num)))))
                num = ''
            if ch != ' ':
                out.append(ch)
            else:
                out.append(' ')
    return ''.join(out).replace(' ', ' ').strip()

lines = ['// Generated by scripts/gen-virtue-glyphs.py from Noto Serif CJK JP Bold (SIL OFL 1.1). Do not edit by hand.',
         '// Outlined kanji paths in a 1000 unit em box (y down), so the katana never depends on installed fonts.',
         'export const VIRTUE_GLYPHS: Record<string, string> = {']
for c in CHARS:
    name = cmap[ord(c)]
    pen = SVGPathPen(gs)
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 880)))  # flip y; ideographic em box spans -120..880
    d = pen.getCommands()
    lines.append(f"  '{c}': '{round_path(d)}',")
lines.append('};')
open('src/data/virtue-glyphs.ts', 'w').write('\n'.join(lines) + '\n')
print('wrote', len(CHARS), 'glyphs')
